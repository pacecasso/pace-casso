function routeKm(coords: [number, number][]): number {
  let meters = 0;
  for (let i = 1; i < coords.length; i++) meters += haversineMeters(coords[i - 1]!, coords[i]!);
  return meters / 1000;
}

function candidateFrom(coords: [number, number][], intent: string): MapNativeCandidate {
  let minLat = Infinity, maxLat = -Infinity, minLng = Infinity, maxLng = -Infinity;
  for (const [lat, lng] of coords) {
    minLat = Math.min(minLat, lat); maxLat = Math.max(maxLat, lat);
    minLng = Math.min(minLng, lng); maxLng = Math.max(maxLng, lng);
  }
  return {
    placement: { center: [(minLat + maxLat) / 2, (minLng + maxLng) / 2], rotationDeg: 29, scale: 1 },
    anchors: coords,
    km: routeKm(coords),
    designIntent: intent,
    kind: "street-design",
    routeMode: "direct-grid",
  };
}

function routeLine(coords: [number, number][]): RouteLineString {
  return { coordinates: coords, distanceMeters: routeKm(coords) * 1000, blockWaypoints: coords };
}

